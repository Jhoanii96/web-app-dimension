                            {
                                loop_attempts = false;
                            }
                        }

                    } while (loop_attempts == false && num_attempts < 3);
                    string moduleid = DecryptString(NewReportSetting[0].rese_idmodule);
                    string code_report = EncryptMD5(Guid.NewGuid().ToString());
                    string data = $"EXECUTE [velkpi].[PRC_INSERT_CNF_APPS] '{NewReportSetting[i].rese_reportmenuenname ?? ""}', " +
                        $"'{NewReportSetting[i].rese_reportmenuesname ?? ""}', " +
                        $"'{(NewReportSetting[i].rese_reportenname ?? "")}', " +
                        $"'{Uri.UnescapeDataString(NewReportSetting[i].rese_reportenurl ?? "")}', " +
                        $"'{(NewReportSetting[i].rese_reportesname ?? "")}', " +
                        $"'{Uri.UnescapeDataString(NewReportSetting[i].rese_reportesurl ?? "")}', " +
                        $"{moduleid}, " +
                        $"'{code_report}'; ";
                    SqlCommand command = new SqlCommand(data, __Sql)
                    {
                        CommandTimeout = 3600
                    };
                    command.ExecuteReader();
                    __Sql.Close();

                }

                error.Error = false;
                error.Number = 1;
                error.Message = "The execution was seccessful!";

                var json = JsonConvert.SerializeObject(error,
                Formatting.None,
                new JsonSerializerSettings()
                {
